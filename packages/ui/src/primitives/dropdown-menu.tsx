        "group/dropdown-menu-item relative flex cursor-default items-center h-7 gap-2.5 rounded-control px-2 text-[12px] leading-none text-text outline-none select-none data-[highlighted]:bg-panel-2 data-[disabled]:pointer-events-none data-[disabled]:opacity-[0.38] [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-3.5 data-[inset]:pl-7 data-[variant=destructive]:text-danger",
        className
